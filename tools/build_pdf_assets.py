#!/usr/bin/env python3
"""Run from anywhere:  python3 tools/build_pdf_assets.py

Pack the fonts in netlify/lib/fonts and the logo into netlify/lib/pdf-assets.mjs, so the order
documents (receipt, care and warranty) can be drawn by the Netlify function without reading files."""
import base64, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FILES = {
    "serif": "netlify/lib/fonts/cormorant-garamond-latin-500-normal.woff",
    "serifItalic": "netlify/lib/fonts/cormorant-garamond-latin-400-italic.woff",
    "sans": "netlify/lib/fonts/jost-latin-400-normal.woff",
    "sansMedium": "netlify/lib/fonts/jost-latin-500-normal.woff",
    "logo": "images/logo-transparent.png",
}
out = ["// Generated by tools/build_pdf_assets.py. Fonts: Cormorant Garamond and Jost (SIL Open Font License).",
       "export const ASSETS = {"]
for key, path in FILES.items():
    data = base64.b64encode(open(os.path.join(ROOT, path), "rb").read()).decode()
    out.append(f"  {key}: '{data}',")
out.append("};\n")
open(os.path.join(ROOT, "netlify/lib/pdf-assets.mjs"), "w").write("\n".join(out))
print("ok")
