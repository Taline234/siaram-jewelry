#!/usr/bin/env python3
"""Run from the repository root:  python3 tools/build_voucher_assets.py

Turns the owner's Canva gift voucher cards (tools/voucher-templates/voucher.png and message.png, A5 landscape) into
supabase/functions/_shared/voucher-assets.mjs, which voucherPdf() in documents.mjs draws on. The Canva link in the
terms line is painted over here; the PDF writes the website's terms address in its place."""
import base64
import io
from PIL import Image, ImageDraw

PAPER = (241, 238, 233)
TERMS_LINE = {"voucher": (300, 1128, 1460, 1178), "message": (300, 1110, 1460, 1160)}
out = ["// Generated by tools/build_voucher_assets.py from the owner's Canva gift voucher cards.", "export const VOUCHER_ASSETS = {"]
for name, box in TERMS_LINE.items():
    im = Image.open(f"tools/voucher-templates/{name}.png").convert("RGB")
    ImageDraw.Draw(im).rectangle(box, fill=PAPER)
    im = im.resize((1400, round(1400 * im.size[1] / im.size[0])), Image.LANCZOS)
    buf = io.BytesIO()
    im.save(buf, "JPEG", quality=86, optimize=True)
    out.append(f"  {name}: '{base64.b64encode(buf.getvalue()).decode()}',")
    print(name, len(buf.getvalue()) // 1024, "KB")
out.append("};")
open("supabase/functions/_shared/voucher-assets.mjs", "w").write("\n".join(out) + "\n")
